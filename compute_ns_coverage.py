def validate_syllabus_knowledge(
    syllabus_knowledges: list,
    ECSF_knowledge_set: list
) -> bool:
    ecsf_knowledge = set(ECSF_knowledge_set)

    for knowledge, score in syllabus_knowledges:
        if knowledge not in ecsf_knowledge:
            print("Syllabus knowledge not in ECSF taxonomy:", knowledge)
            return False

        if not isinstance(score, (int, float)) or score < 0 or score > 1:
            print("Invalid weight for knowledge:", knowledge, "->", score)
            return False

    return True


def validate_ECSF_Knowledge(ECSF_profiles: dict,ECSF_Knowledge_set: list) -> bool:
    ecsf_knowledge = set(ECSF_Knowledge_set)
    for profile_name,profile_knowledge in ECSF_profiles.items():
        if not set(profile_knowledge).issubset(ecsf_knowledge):
            print("Profile ",profile_name,"is unconsistent. Check the knowledge.")
            return False

    return True

def compute_coverage(profile_name, ECSF_Target_profile:list, syllabus_knowledges:list) -> float:
    profile_knowledge = set(ECSF_Target_profile)
    num_knowledge_in_profile = len(profile_knowledge)
    coverage = 0.0
